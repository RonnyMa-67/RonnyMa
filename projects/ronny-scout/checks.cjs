const assert = require('node:assert/strict');
const d = require('./data.js');
const sample = d.samples();
assert.equal(sample.length, 10);
assert(sample.every(r => r.cells.length === 10 && r.synthetic));
assert.deepEqual(d.parseDelimited('a,b\r\n"x,y","line\n""quote"""', ','), [['a','b'],['x,y','line\n"quote"']]);
assert.throws(() => d.parseDelimited('"unclosed', ','));
assert.throws(() => d.parseDelimited('"closed"unexpected', ','));
assert.throws(() => d.parseImport('公司,国家\nx,SG,extra'));
assert.throws(() => d.parseImport('company,country'));
assert.throws(() => d.parseImport('name,random\nx,y'));
assert.throws(() => d.parseImport('公司,国家\n,SG'));
assert.equal(d.parseImport('虚构独立线索\n第二条').length, 2);
const imported = d.parseImport('\uFEFF公司\t国家\t产品\t评级\n虚构公司\t新加坡\t咖啡机\tP1')[0];
assert.equal(imported.cells[8], '待核实');
assert.equal(imported.category, '咖啡机');
assert(imported.raw.includes('P1'));
const roundTrip = d.parseImport(d.csv(sample));
assert.equal(roundTrip.length, 10);
assert.equal(roundTrip[0].cells[1], sample[0].cells[1]);
assert(roundTrip.every(r => r.cells[8] === '待核实'));
assert.equal(d.parseDelimited(d.csv(sample), ',')[0].length, 10);
const dangerous = d.parseImport('公司,国家\n=1+1,SG');
assert(d.csv(dangerous).includes('"\'=1+1"'));
const q = d.audit([...dangerous, ...dangerous, ...d.parseImport('missing')]);
assert.equal(q.duplicates, 1);
assert.equal(q.formula, 2);
assert.equal(q.missingCountry, 1);
assert.equal(q.pending, 3);
assert.throws(() => d.parseImport('x'.repeat(2*1024*1024+1)));
assert.throws(() => d.parseImport(Array(1001).fill('x').join('\n')));
console.log('Passed: fictional data, A–J schema, CSV/TSV/plain text, quoted fields, invalid inputs, round trip, formula protection, quality checks and limits.');
